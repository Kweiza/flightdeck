// unicode61.go 의 가름표 표가 SQLite FTS5 의 unicode61 토크나이저와 코드포인트 하나까지 같은지 SQLite 에 직접 물어 잰다.
//
// ★ 왜 Go 의 unicode 범주로 안 가르나. unicode61 의 범주 표는 Unicode 6.1 에 멈춰 있다(이미 지은 색인과 맞아야 해서
// SQLite 가 안 바꾼다). 그 뒤에 생긴 글자는 그 표에서 「미지정」이고 unicode61 은 미지정을 낱말 글자로 본다 - 이모지
// `🦊`(So, Unicode 9.0)가 낱말이고 `©`(So, 1.1)는 가름표다. 범주가 바뀐 글자도 있다(U+19B0 등은 6.1 에서 Mc 라
// 가름표, 지금은 Lo). 범주로 가르면 `🦊` 만 친 검색이 Postgres 판에서 조각 0개가 되어 SQLite 판이 찾는 판단을 놓친다.
//
// 표를 다시 짓는 법: FD_WRITE_UNICODE61=<경로> 를 주고 이 시험을 돌리면 그 경로에 unicode61.go 를 쓴다.

// unicode61TokenChars 는 코드포인트마다 unicode61 이 낱말 글자로 두는가다(SQLite 에 물은 값). 떼어 내는 결합
// 기호(remove_diacritics)는 거짓이다 - SearchTerms 는 그것을 가름표로 둔다(unicode61.go 의 ★).
func unicode61TokenChars(t *testing.T) []bool {
	t.Helper()
	db, err := sql.Open("sqlite", ":memory:")
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	db.SetMaxOpenConns(1) // :memory: 는 연결마다 다른 DB 다
	if _, err := db.Exec(`CREATE VIRTUAL TABLE probe USING fts5(x)`); err != nil {
		t.Fatal(err)
	}
	// 글 하나에 코드포인트 4096개를 「x<c>x 」 꼴로 잇는다. 토큰 열을 차례로 읽으면 c 마다 셋 중 하나다:
	// 「x<접은 c>x」 하나(낱말 글자) · 「xx」 하나(떼어 낸 결합 기호) · 「x」 「x」 둘(가름표).
	const per = 4096
	var docs [][]rune
	for lo := rune(1); lo <= utf8.MaxRune; lo += per {
		var cps []rune
		for cp := lo; cp < lo+per && cp <= utf8.MaxRune; cp++ {
			if utf8.ValidRune(cp) {
				cps = append(cps, cp)
			}
		}
		docs = append(docs, cps)
	}
	tx, err := db.Begin()
	if err != nil {
		t.Fatal(err)
	}
	for i, cps := range docs {
		var b strings.Builder
		for _, cp := range cps {
			b.WriteString("x")
			b.WriteRune(cp)
			b.WriteString("x ")
		}
		if _, err := tx.Exec(`INSERT INTO probe(rowid, x) VALUES (?, ?)`, i, b.String()); err != nil {
			t.Fatal(err)
		}
	}
	if err := tx.Commit(); err != nil {
		t.Fatal(err)
	}
	if _, err := db.Exec(`CREATE VIRTUAL TABLE probe_v USING fts5vocab(probe, 'instance')`); err != nil {
		t.Fatal(err)
	}
	rows, err := db.Query(`SELECT doc, term FROM probe_v ORDER BY doc, "offset"`)
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	terms := make([][]string, len(docs))
	for rows.Next() {
		var doc int
		var term string
		if err := rows.Scan(&doc, &term); err != nil {
			t.Fatal(err)
		}
		terms[doc] = append(terms[doc], term)
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
	tok := make([]bool, utf8.MaxRune+1) // 0(NUL)은 거짓이다 - 글에 못 싣고, 가름표로 둔다
	for i, cps := range docs {
		ts := terms[i]
		for _, cp := range cps {
			if len(ts) == 0 {
				t.Fatalf("U+%04X 에서 토큰 열이 일찍 끝났다", cp)
			}
			switch {
			case ts[0] == "x":
				if len(ts) < 2 || ts[1] != "x" {
					t.Fatalf("U+%04X: 가름표 뒤 토큰이 %q 다", cp, ts[:min(2, len(ts))])
				}
				ts = ts[2:]
			case ts[0] == "xx":
				ts = ts[1:]
			case len(ts[0]) > 2 && strings.HasPrefix(ts[0], "x") && strings.HasSuffix(ts[0], "x"):
				tok[cp] = true
				ts = ts[1:]
			default:
				t.Fatalf("U+%04X: 읽을 수 없는 토큰 %q", cp, ts[0])
			}
		}
		if len(ts) != 0 {
			t.Fatalf("글 %d 의 토큰이 %d개 남았다", i, len(ts))
		}
	}
	return tok
}

// TestSearchTermsMatchUnicode61 은 SearchTerms 의 가름표 판정이 코드포인트 전부에서 unicode61 과 같은지 잰다.
func TestSearchTermsMatchUnicode61(t *testing.T) {
	tok := unicode61TokenChars(t)
	if path := os.Getenv("FD_WRITE_UNICODE61"); path != "" {
		writeUnicode61Table(t, path, tok)
		return
	}
	var bad []string
	n := 0
	for cp := rune(0); cp <= utf8.MaxRune; cp++ {
		if !utf8.ValidRune(cp) {
			continue
		}
		n++
		// 표만이 아니라 SearchTerms 가 그 표로 가르는지까지 본다: 낱말 글자면 「x<c>x」 가 조각 하나로 남는다.
		if got := len(SearchTerms("x"+string(cp)+"x")) == 1; got != tok[cp] {
			bad = append(bad, fmt.Sprintf("U+%04X(SearchTerms 낱말 %v, SQLite 낱말 %v)", cp, got, tok[cp]))
		}
	}
	if len(bad) > 0 {
		t.Fatalf("코드포인트 %d개 중 %d개가 unicode61 과 다르다(FD_WRITE_UNICODE61 로 표를 다시 지어라): %s",
			n, len(bad), strings.Join(bad[:min(20, len(bad))], ", "))
	}
	if n != utf8.MaxRune+1-(0xDFFF-0xD800+1) {
		t.Fatalf("잰 코드포인트가 %d개다", n)
	}
}

// writeUnicode61Table 은 tok 의 거짓 구간을 unicode61.go 로 쓴다.
func writeUnicode61Table(t *testing.T, path string, tok []bool) {
	t.Helper()
	var ranges [][2]rune
	for cp := rune(0); cp <= utf8.MaxRune; cp++ {
		if tok[cp] {
			continue
		}
		if !utf8.ValidRune(cp) { // 서로게이트는 Go 글자열에 못 든다 - 앞 구간에 이어 붙여 표를 짧게 둔다
			if k := len(ranges); k > 0 && ranges[k-1][1] == cp-1 {
				ranges[k-1][1] = cp
			}
			continue
		}
		if k := len(ranges); k > 0 && ranges[k-1][1] == cp-1 {
			ranges[k-1][1] = cp
		} else {
			ranges = append(ranges, [2]rune{cp, cp})
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by TestSearchTermsMatchUnicode61 with FD_WRITE_UNICODE61 set; DO NOT EDIT.\n\n")
	b.WriteString("package store\n\n")
	b.WriteString("// unicode61Separators 는 SQLite FTS5 의 기본 토크나이저(unicode61, remove_diacritics=1)가 낱말 글자로 두지 않는\n")
	b.WriteString("// 코드포인트의 닫힌 구간이다(오름차순). 떼어 내는 결합 기호도 든다. 짓는 법과 까닭은 unicode61_test.go 에 있다.\n")
	fmt.Fprintf(&b, "// 구간 %d개.\n", len(ranges))
	b.WriteString("var unicode61Separators = [...]runeRange{\n")
	for i, r := range ranges {
		if i%4 == 0 {
			b.WriteString("\t")
		}
		fmt.Fprintf(&b, "{0x%04X, 0x%04X},", r[0], r[1])
		if i%4 == 3 || i == len(ranges)-1 {
			b.WriteString("\n")
		} else {
			b.WriteString(" ")
		}
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, src, 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("%s 에 구간 %d개를 썼다", path, len(ranges))
}
